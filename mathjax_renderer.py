"""Server-side MathJax SVG renderer used only for the Word WMF preview.

The editable MathType OLE is still generated by latex2mtef.py/mtef_encode.py.
MathJax is used for the preview image because it handles cases, matrices,
integrals, stretchy delimiters and TeX spacing much more faithfully than
Matplotlib MathText.
"""
from __future__ import annotations

import atexit
import io
import json
import os
import re
import select
import subprocess
import tempfile
import threading
from functools import lru_cache
from pathlib import Path

from latex_normalize import normalize_sqrt_groups

import cairosvg
from PIL import Image, ImageOps

_ROOT = Path(__file__).resolve().parent
_SERVER = _ROOT / "mathjax_server.mjs"
_NODE = os.getenv("MATHTYPE_NODE_BIN", "node")
_TIMEOUT = max(2.0, float(os.getenv("MATHTYPE_MATHJAX_TIMEOUT", "30")))
_PERSISTENT = os.getenv("MATHTYPE_MATHJAX_PERSISTENT", "true").strip().lower() in {
    "1", "true", "yes", "on"
}
try:
    _NODE_HEAP_MB = max(64, int(os.getenv("MATHTYPE_NODE_HEAP_MB", "256")))
except (TypeError, ValueError):
    _NODE_HEAP_MB = 256
_EX_PER_EM = 0.5  # Node renderer is configured with EM=16, EX=8.

_LOCK = threading.RLock()
_PROCESS: subprocess.Popen[str] | None = None
_STDERR_PATH: str | None = None  # log stderr cua Node de chan doan khi no chet

_WIDTH_RE = re.compile(r'<svg\b[^>]*\bwidth="([0-9.]+)ex"', re.I)
_HEIGHT_RE = re.compile(r'<svg\b[^>]*\bheight="([0-9.]+)ex"', re.I)
_ALIGN_RE = re.compile(r'vertical-align:\s*(-?[0-9.]+)ex', re.I)


def _normalize(latex: str) -> str:
    text = normalize_sqrt_groups((latex or "").strip())
    text = text.replace("≤", r"\le ").replace("≥", r"\ge ").replace("≠", r"\ne ")
    text = text.replace(r"\leqslant", r"\leq").replace(r"\geqslant", r"\geq")
    text = re.sub(r"\\ge(?![A-Za-z])", r"\\geq", text)
    text = re.sub(r"\\le(?![A-Za-z])", r"\\leq", text)
    text = re.sub(r"\\ne(?![A-Za-z])", r"\\neq", text)
    text = re.sub(r"(?<![<\\])<\s*=", r"\\le ", text)
    text = re.sub(r"(?<![>\\])>\s*=", r"\\ge ", text)
    text = re.sub(
        r"(\\(?:int|sum|prod)\s*\\limits)\s*\{([^{}]+)\}\s*\^\s*\{",
        r"\1_{\2}^{",
        text,
    )
    # MathJax supports dfrac/tfrac. cfrac is not guaranteed in the small
    # direct TeX package set, so map it to dfrac for a safe preview.
    text = text.replace(r"\cfrac", r"\dfrac")
    return text


def _start_process() -> subprocess.Popen[str]:
    global _PROCESS, _STDERR_PATH
    if _PROCESS is not None and _PROCESS.poll() is None:
        return _PROCESS
    if not _SERVER.exists():
        raise RuntimeError(f"Missing MathJax server: {_SERVER}")
    # Ghi stderr cua Node ra file tam de doc lai khi tien trinh chet (thieu
    # node_modules, OOM, loi import...). Doc tu file tranh deadlock so voi PIPE.
    fd, _STDERR_PATH = tempfile.mkstemp(prefix="mathjax_stderr_", suffix=".log")
    stderr_file = os.fdopen(fd, "w", encoding="utf-8")
    node_cmd = [
        _NODE,
        f"--max-old-space-size={_NODE_HEAP_MB}",
        str(_SERVER),
    ]
    _PROCESS = subprocess.Popen(
        node_cmd,
        cwd=str(_ROOT),
        stdin=subprocess.PIPE,
        stdout=subprocess.PIPE,
        stderr=stderr_file,
        text=True,
        encoding="utf-8",
        bufsize=1,
        env=os.environ.copy(),
    )
    stderr_file.close()  # tien trinh con da giu fd; ta chi can duong dan de doc
    return _PROCESS


def _read_stderr_tail(limit: int = 1500) -> str:
    """Doc phan cuoi stderr cua Node de dua vao thong bao loi."""
    path = _STDERR_PATH
    if not path or not os.path.exists(path):
        return ""
    try:
        with open(path, "r", encoding="utf-8", errors="replace") as fh:
            text = fh.read().strip()
    except Exception:
        return ""
    if len(text) > limit:
        text = "..." + text[-limit:]
    return text


def _stop_process(cleanup_log: bool = True) -> None:
    global _PROCESS, _STDERR_PATH
    proc, _PROCESS = _PROCESS, None
    if proc is not None:
        try:
            proc.terminate()
            proc.wait(timeout=2)
        except Exception:
            try:
                proc.kill()
            except Exception:
                pass
    if cleanup_log and _STDERR_PATH:
        try:
            os.remove(_STDERR_PATH)
        except Exception:
            pass
        _STDERR_PATH = None


atexit.register(_stop_process)


def _request_svg(latex: str) -> str:
    payload = json.dumps({"latex": latex, "display": False}, ensure_ascii=False)
    last_error: Exception | None = None
    for _ in range(2):
        with _LOCK:
            try:
                proc = _start_process()
                assert proc.stdin is not None and proc.stdout is not None
                try:
                    proc.stdin.write(payload + "\n")
                    proc.stdin.flush()
                except (BrokenPipeError, ValueError):
                    # Node da chet truoc khi ta ghi duoc -> lay ly do tu stderr.
                    raise RuntimeError(_stopped_message(proc))
                ready, _, _ = select.select([proc.stdout], [], [], _TIMEOUT)
                if not ready:
                    raise TimeoutError("MathJax renderer timed out")
                line = proc.stdout.readline()
                if not line:
                    raise RuntimeError(_stopped_message(proc))
                data = json.loads(line)
                if not data.get("ok"):
                    raise RuntimeError(data.get("error") or "MathJax render failed")
                svg = str(data["svg"])
                if not _PERSISTENT:
                    _stop_process()
                return svg
            except Exception as exc:
                last_error = exc
                _stop_process()
    raise RuntimeError(str(last_error or "MathJax render failed"))


def _stopped_message(proc: subprocess.Popen) -> str:
    """Thong bao loi giau thong tin khi Node chet: kem ma thoat + stderr."""
    code = proc.poll()
    stderr = _read_stderr_tail()
    hint = ""
    if stderr and ("ERR_MODULE_NOT_FOUND" in stderr or "Cannot find package" in stderr):
        hint = (" | Thieu node_modules: chay 'npm install --omit=dev' o thu muc "
                "chua package.json, hoac deploy bang Dockerfile da co buoc npm install.")
    elif code is not None and code < 0:
        hint = (f" | Node bi kill boi tin hieu {-code} (thuong la het RAM tren "
                "Render Free 512MB).")
    parts = ["MathJax renderer stopped unexpectedly"]
    if code is not None:
        parts.append(f"exit={code}")
    if stderr:
        parts.append(f"stderr: {stderr}")
    return " | ".join(parts) + hint


def _metrics(svg: str, full_pt: float) -> tuple[float, float, float]:
    mw = _WIDTH_RE.search(svg)
    mh = _HEIGHT_RE.search(svg)
    if not mw or not mh:
        raise ValueError("MathJax SVG has no ex dimensions")
    width_ex = float(mw.group(1))
    height_ex = float(mh.group(1))
    ma = _ALIGN_RE.search(svg)
    align_ex = float(ma.group(1)) if ma else 0.0
    ex_pt = float(full_pt) * _EX_PER_EM
    width_pt = max(1.0, width_ex * ex_pt)
    height_pt = max(1.0, height_ex * ex_pt)
    depth_pt = max(0.0, -align_ex * ex_pt)
    return width_pt, height_pt, min(depth_pt, height_pt)


@lru_cache(maxsize=768)
def _render_cached(latex: str, full_pt: float, dpi: int, pad_px: int):
    svg = _request_svg(_normalize(latex))
    width_pt, height_pt, depth_pt = _metrics(svg, full_pt)
    width_px = max(1, round(width_pt * dpi / 72.0))
    height_px = max(1, round(height_pt * dpi / 72.0))
    png = cairosvg.svg2png(
        bytestring=svg.encode("utf-8"),
        output_width=width_px,
        output_height=height_px,
        background_color="white",
    )
    image = Image.open(io.BytesIO(png)).convert("RGB")
    if pad_px:
        image = ImageOps.expand(image, border=pad_px, fill="white")
        pad_pt = pad_px * 72.0 / dpi
        width_pt += 2 * pad_pt
        height_pt += 2 * pad_pt
        depth_pt += pad_pt
    out = io.BytesIO()
    image.save(out, "PNG")
    return out.getvalue(), width_pt, height_pt, depth_pt


def render_mathjax(latex: str, full_pt: float, dpi: int, pad_px: int = 1):
    """Return (PIL.Image RGB, width_pt, height_pt, depth_pt), or raise."""
    png, width_pt, height_pt, depth_pt = _render_cached(
        latex or "", float(full_pt), int(dpi), int(pad_px)
    )
    return Image.open(io.BytesIO(png)).convert("RGB"), width_pt, height_pt, depth_pt


def mathjax_info() -> dict:
    node_modules = _ROOT / "node_modules" / "@mathjax" / "src"
    return {
        "engine": "mathjax-svg",
        "font": os.getenv("MATHTYPE_MATHJAX_FONT", "mathjax-termes"),
        "node": _NODE,
        "persistent": _PERSISTENT,
        "node_heap_mb": _NODE_HEAP_MB,
        "server_exists": _SERVER.exists(),
        "node_modules_present": node_modules.exists(),
    }
